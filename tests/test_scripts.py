from datetime import date

import pytest

from pdfmarker.scripts import ScriptError, calculate, calculation_inputs, commit_value, format_display

MISMATCH = "The value entered does not match the format of the field [ {} ]"


def lookup(values):
    """values_of() over a flat {qualified name: value} form."""
    return lambda name: [v for k, v in values.items() if k == name or k.startswith(name + ".")]


def commit(keystroke, value, validate="", name="Field"):
    return commit_value(name, keystroke, validate, value)


def rejection(keystroke, value, validate="", name="Field"):
    with pytest.raises(ScriptError) as error:
        commit_value(name, keystroke, validate, value)
    return str(error.value)


# Recognising scripts

@pytest.mark.parametrize("script", [
    'event.value = this.getField("a").value * 2;',
    'AFNumber_Format(2, 0, 0, 0, "$", true); app.alert("hi");',
    'MyNumber_Format(2);',
    'AFNumber_Format(2, 0, 0, 0, "$", true',
    'AFNumber_Format(2, 0, 0, 0, "$, true);',
    'AFNumber_Format(2 0);',
    'AFNumber_Format(x);',
    'AFNumber_Format();',
    'AFNumber_Format([1], 0);',
    '/* unterminated AFNumber_Format(2);',
    '// just a comment',
    '',
    None,
    'AFDate_Format(99);',
    'AFSpecial_Format(4);',
    'AFNumber_Keystroke(2, 0, 0, 0, "", true);',
])
def test_unrecognised_format_scripts_return_none(script):
    assert format_display(script, "12") is None


def test_comments_semicolons_and_literals_are_understood():
    script = """// Generated by Acrobat
    /* number */ AFNumber_Format(2, 0, 0, 0, '\\u20ac', false);;
    """
    assert format_display(script, "1234.5") == "1,234.50€"
    assert format_display('AFNumber_Format(2, 2, 0, 0, " \\x80\\u20AC", false)', "1") == "1,00 \x80€"
    assert format_display('AFNumber_Format("1", 0, 0, 0, "", 1)', "2.25") == "2.3"


def test_recognised_script_with_empty_value_is_blank():
    assert format_display('AFNumber_Format(2, 0, 0, 0, "$", true);', "") == ""
    assert format_display('AFDate_FormatEx("mm/dd/yyyy");', "") == ""


