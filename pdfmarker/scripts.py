# Calculations

_AGGREGATES = {"SUM": sum, "PRD": math.prod, "AVG": lambda xs: sum(xs) / len(xs), "MIN": min, "MAX": max}
_OPERATORS = {"+": operator.add, "-": operator.sub, "*": operator.mul, "/": operator.truediv}
_SFN = re.compile(r"BVCALC(.*?)EVCALC", re.S)
_SFN_TOKEN = re.compile(r"\s+|(?P<op>[-+*/()])|(?P<word>(?:\\.|[^\s\\()*/+-])+)", re.S)


def _sfn_parse(text: str):
    """(tree, field names) for a simplified field notation expression, or None.

    Leaves are Decimals and ("field", name); other nodes are ("neg", node) and
    (operator, left, right). A backslash escapes the next character of a name.
    """
    tokens, names, pos = [], set(), 0
    while pos < len(text):
        match = _SFN_TOKEN.match(text, pos)
        if not match:
            return None
        pos = match.end()
        if match["op"]:
            tokens.append(match["op"])
        elif word := match["word"]:
            if re.fullmatch(r"[0-9]+\.?[0-9]*|\.[0-9]+", word):
                tokens.append(Decimal(word))
            else:
                names.add(name := re.sub(r"\\(.)", r"\1", word, flags=re.S))
                tokens.append(("field", name))
    tokens.append(None)
    index = 0

    def binary(operand, symbols):
        def parse():
            nonlocal index
            node = operand()
            while tokens[index] in symbols:
                symbol = tokens[index]
                index += 1
                node = (symbol, node, operand())
            return node
        return parse

    def factor():
        nonlocal index
        token = tokens[index]
        index += 1
        if token in ("+", "-"):
            node = factor()
            return ("neg", node) if token == "-" else node
        if token == "(":
            node = expression()
            if tokens[index] != ")":
                raise _Unsupported
            index += 1
            return node
        if token is None or isinstance(token, str):
            raise _Unsupported
        return token

    expression = binary(binary(factor, ("*", "/")), ("+", "-"))
    try:
        tree = expression()
    except (_Unsupported, RecursionError):
        return None
    return (tree, names) if tokens[index] is None else None


def _evaluate(node, numbers_of):
    if isinstance(node, Decimal):
        return node
    if node[0] == "field":
        return sum(numbers_of(node[1]), Decimal(0))
    if node[0] == "neg":
        return -_evaluate(node[1], numbers_of)
    return _OPERATORS[node[0]](_evaluate(node[1], numbers_of), _evaluate(node[2], numbers_of))


def _simple_calls(script: str):
    """[(function, field names)] for a script of AFSimple_Calculate calls, else None."""
    calls = _parse(script)
    if not calls:
        return None
    plan = []
    for name, args in calls:
        if name != "AFSimple_Calculate" or len(args) != 2 or not isinstance(args[0], str):
            return None
        function, fields = args[0].upper(), args[1]
        fields = fields.split(",") if isinstance(fields, str) else fields
        if function not in _AGGREGATES or not isinstance(fields, list) \
                or not all(isinstance(f, str) for f in fields):
            return None
        plan.append((function, [f.strip() for f in fields if f.strip()]))
    return plan


def _calculation(script: str | None):
    """(evaluate(numbers_of), input names) for a supported Calculate script, else None."""
    if not script:
        return None
    if match := _SFN.search(script):
        parsed = _sfn_parse(match[1])
        return None if parsed is None else (partial(_evaluate, parsed[0]), parsed[1])
    plan = _simple_calls(script)
    if plan is None:
        return None

    def evaluate(numbers_of):
        for function, names in plan:
            numbers = [n for name in names for n in numbers_of(name)]
            result = _AGGREGATES[function](numbers) if numbers else Decimal(0)
        return result
    return evaluate, {name for _, names in plan for name in names}


# Public API

def format_display(script: str, value: str) -> str | None:
    """Format action (/AA /F). Return the display text for `value`, or None if the
    script isn't made only of recognised built-in calls (caller then shows the raw value).
    Empty value -> "" for recognised scripts."""
    calls = _calls(script, _FORMAT, 1)
    if calls is None:
        return None
    if not value:
        return ""
    try:
        for handler, args in calls:
            value = handler(value, *args)
    except _Unsupported:
        return None
    return value


def commit_value(name: str, keystroke: str, validate: str, value: str) -> str:
    """Run the Keystroke action (/AA /K) in commit mode (willCommit=true), then the
    Validate action (/AA /V). Return the value to store; raise ScriptError to reject.
    `name` is the field name for messages. Empty/None scripts or unrecognised scripts
    pass the value through unchanged. Empty value is always accepted."""
    if not value:
        return ""
    for script, table in ((keystroke, _KEYSTROKE), (validate, _VALIDATE)):
        result = value
        try:
            for handler, args in _calls(script, table, 2) or ():
                result = handler(name, result, *args)
        except _Unsupported:
            continue
        value = result
    return value


def calculate(script: str, values_of: Callable[[str], list[str]]) -> str | None:
    """Calculate action (/AA /C). `values_of(name)` returns the current values of all
    terminal fields whose fully qualified name equals `name` or starts with `name + "."`
    (Acrobat group names); empty list if none. Return the new value as a string, or None
    if unsupported.

    Blank and non-numeric values count as 0, as in Acrobat. A result that is not a
    finite number (division by zero) is returned as "", which is how such a field
    ends up in practice. A field name in simplified field notation stands for the
    sum of its values when it names a group.
    """
    plan = _calculation(script)
    if plan is None:
        return None
    try:
        with localcontext(_CONTEXT):
            return _number_text(plan[0](lambda name: [_make_number(v) for v in values_of(name)]))
    except ArithmeticError:
        return ""
    except RecursionError:
        return None


def calculation_inputs(script: str) -> set[str] | None:
    """Field names a recognised Calculate script reads (for dependency info); None if unsupported."""
    plan = _calculation(script)
    return None if plan is None else plan[1]
