"""Acrobat form scripts, recognised rather than executed.

Fillable PDFs attach JavaScript to fields for display formats, validation and
totals. Nearly all of it is generated by Acrobat as calls to its built-in AF*
functions, so those calls are parsed and reimplemented natively. Any other
script is reported as unsupported; no JavaScript is ever run.
"""
from __future__ import annotations

import inspect
import math
import operator
import re
from collections.abc import Callable
from datetime import date, datetime
from decimal import ROUND_HALF_UP, Context, Decimal, localcontext
from functools import cache, partial


class ScriptError(ValueError):
    """User-facing rejection message, Acrobat-style wording."""


class _Unsupported(Exception):
    pass


# Script parsing

_JS = re.compile(r"""
    \s+ | //[^\n]* | /\*.*?\*/
  | (?P<num>(?:\d+\.?\d*|\.\d+)(?:[eE][+-]?\d+)?)
  | (?P<str>"(?:[^"\\\n]|\\.)*"|'(?:[^'\\\n]|\\.)*')
  | (?P<word>[A-Za-z_$][\w$]*)
  | (?P<op>[()\[\],;+-])
""", re.X | re.S)
_JS_ESCAPE = re.compile(r"\\(u[0-9a-fA-F]{4}|x[0-9a-fA-F]{2}|\r\n|.)", re.S)
_JS_ESCAPES = {"n": "\n", "t": "\t", "r": "\r", "b": "\b", "f": "\f", "v": "\v", "0": "\0",
               "\n": "", "\r": "", "\r\n": ""}


def _unescape(body: str) -> str:
    text = _JS_ESCAPE.sub(lambda m: chr(int(m[1][1:], 16)) if len(m[1]) > 2
                          else _JS_ESCAPES.get(m[1], m[1]), body)
    return text.encode("utf-16", "surrogatepass").decode("utf-16", "replace")


def _parse(script: str):
    """[(name, args)] if the script is only calls with literal arguments, else None."""
    tokens, pos = [], 0
    while pos < len(script):
        match = _JS.match(script, pos)
        if not match:
            return None
        pos = match.end()
        if match.lastgroup:
            tokens.append((match.lastgroup, match[match.lastgroup]))
    tokens.append(("end", ""))
    index = 0

    def take(text=None):
        nonlocal index
        token = tokens[index]
        if text is not None and token[1] != text:
            raise _Unsupported
        index += 1
        return token

    def items(close):
        found = []
        while tokens[index][1] != close:
            found.append(value())
            if tokens[index][1] != close:
                take(",")
        take(close)
        return found

    def value():
        kind, text = take()
        if kind == "num":
            return Decimal(text)
        if kind == "str":
            return _unescape(text[1:-1])
        if text in ("-", "+") and tokens[index][0] == "num":
            number = Decimal(take()[1])
            return number.copy_negate() if text == "-" else number
        if text in ("true", "false"):
            return text == "true"
        if text == "[":
            return items("]")
        if text == "new":
            take("Array")
            take("(")
            return items(")")
        raise _Unsupported

    calls = []
    try:
        while tokens[index][0] != "end":
            kind, name = take()
            if name == ";":
                continue
            if kind != "word":
                raise _Unsupported
            take("(")
            calls.append((name, items(")")))
    except (_Unsupported, RecursionError):
        return None
    return calls


@cache
def _params(handler):
    return tuple(inspect.signature(handler, eval_str=True).parameters.values())


def _coerce(kind, arg):
    """Read a literal argument the way the built-in would."""
    if kind is bool:
        return isinstance(arg, list) or bool(arg)
    if isinstance(arg, list):
        raise TypeError
    if kind is str:
        if isinstance(arg, bool):
            return "true" if arg else "false"
        return _plain(arg) if isinstance(arg, Decimal) else arg
    if kind in (int, Decimal):
        if not isinstance(arg, Decimal):
            arg = Decimal(int(arg) if isinstance(arg, bool) else arg.strip() or 0)
        if not arg.is_finite() or abs(arg.adjusted()) > 15:
            raise ValueError
        return int(arg) if kind is int else arg
    return arg


def _calls(script, table, skip):
    """[(handler, args)] if the script only calls built-ins from table, else None."""
    calls = _parse(script) if script else None
    if not calls:
        return None
    bound = []
    for name, args in calls:
        handler = table.get(name)
        if handler is None:
            return None
        params = _params(handler)[skip:]
        if sum(p.default is p.empty for p in params) > len(args):
            return None
        try:
            bound.append((handler, [_coerce(p.annotation, a) for p, a in zip(params, args)]))
        except (TypeError, ValueError, ArithmeticError):
            return None
    return bound


def _pick(options, index):
    if not 0 <= index < len(options):
        raise _Unsupported
    return options[index]


def _mismatch(name):
    return ScriptError(f"The value entered does not match the format of the field [ {name} ]")


# Numbers

_CONTEXT = Context(prec=60, rounding=ROUND_HALF_UP)
_CURRENCIES = ("$", "€", "£", "¥", "₹", "₩", "₽", "¢")
_SEPARATORS = ((",", "."), ("", "."), (".", ","), ("", ","), ("'", "."))


def _unwrap(text, symbols):
    text = text.strip()
    for symbol in symbols:
        if text.startswith(symbol):
            text = text[len(symbol):].strip()
            break
    for symbol in symbols:
        if text.endswith(symbol):
            text = text[:-len(symbol)].strip()
            break
    return text


def _parse_number(text: str, point: str | None = None, currency: str = "") -> Decimal | None:
    """A typed number, or None.

    Accepts a sign or accounting parentheses, a currency symbol and thousands
    separators in groups of three. Without a given decimal mark, the last of
    "." and "," is the mark unless it repeats, so "1,5" is 1.5.
    """
    text = text.strip()
    negative = text.startswith("(") and text.endswith(")")
    if negative:
        text = text[1:-1]
    symbols = tuple(s for s in (currency.strip(), *_CURRENCIES) if s)
    text = _unwrap(text, symbols)
    if text.startswith(("-", "+")) and not negative:
        negative = text[0] == "-"
        text = _unwrap(text[1:], symbols)
    if point is None:
        dot, comma = text.rfind("."), text.rfind(",")
        if dot >= 0 and comma >= 0:
            point = "." if dot > comma else ","
        else:
            point = "," if text.count(",") == 1 or text.count(".") > 1 else "."
    whole, _, fraction = text.partition(point)
    groups = re.split("[" + re.escape("., '\u00a0\u202f".replace(point, "")) + "]", whole)
    if len(groups) > 1 and not (0 < len(groups[0]) <= 3 and all(len(g) == 3 for g in groups[1:])):
        return None
    digits = "".join(groups)
    if not re.fullmatch(r"[0-9]{1,30}", digits + fraction):
        return None
    number = Decimal(f"{digits or 0}.{fraction or 0}")
    return number.copy_negate() if negative else number


def _make_number(value) -> Decimal:
    """AFMakeNumber for calculations: blanks and text count as 0."""
    number = _parse_number("" if value is None else str(value))
    return Decimal(0) if number is None else number


def _plain(number: Decimal) -> str:
    text = f"{number.normalize(_CONTEXT):f}"
    return "0" if text == "-0" else text


def _number_text(number: Decimal) -> str:
    """Calculation result as field text, with float-style noise rounded away."""
    if number.adjusted() < 40:
        number = number.quantize(Decimal("1E-10"), ROUND_HALF_UP, _CONTEXT)
    return _plain(number)


def _fixed(number: Decimal, places: int, sep_style: int) -> tuple[bool, str]:
    """(negative, unsigned text) rounded half away from zero, in a sepStyle."""
    group, point = _SEPARATORS[min(max(sep_style, 0), 4)]
    rounded = number.quantize(Decimal(1).scaleb(-min(max(places, 0), 20)), ROUND_HALF_UP, _CONTEXT)
    whole, _, fraction = f"{rounded.copy_abs():f}".partition(".")
    whole = f"{int(whole):,}".replace(",", group)
    return rounded < 0, whole + (point + fraction if fraction else "")


def _number_format(value: str, places: int, sep_style: int = 0, neg_style: int = 0,
                   curr_style: int = 0, currency: str = "", prepend: bool = True) -> str:
    number = _parse_number(value)
    if number is None:
        return value
    negative, text = _fixed(number, places, sep_style)
    text = currency + text if prepend else text + currency
    if not negative or neg_style == 1:  # Red without a sign; colour is not shown.
        return text
    return f"({text})" if neg_style in (2, 3) else "-" + text


def _percent_format(value: str, places: int, sep_style: int = 0, prepend: bool = False) -> str:
    number = _parse_number(value)
    if number is None:
        return value
    negative, text = _fixed(number.scaleb(2, _CONTEXT), places, sep_style)
    text = ("-" if negative else "") + text
    return "%" + text if prepend else text + "%"


def _number_keystroke(name: str, value: str, places: int = 2, sep_style: int = 0, neg_style: int = 0,
                      curr_style: int = 0, currency: str = "", prepend: bool = True) -> str:
    number = _parse_number(value, "," if sep_style in (2, 3) else ".", currency)
    if number is None:
        raise _mismatch(name)
    return _plain(number)


def _percent_keystroke(name: str, value: str, places: int = 2, sep_style: int = 0) -> str:
    text = value.strip()
    number = _parse_number(text.removesuffix("%"), "," if sep_style in (2, 3) else ".")
    if number is None:
        raise _mismatch(name)
    return _plain(number.scaleb(-2, _CONTEXT) if text.endswith("%") else number)


def _range_validate(name: str, value: str, above: bool, low: Decimal,
                    below: bool = False, high: Decimal = Decimal(0)) -> str:
    number = _parse_number(value)
    if number is None:
        raise _mismatch(name)
    limits = []
    if above:
        limits.append(f"greater than or equal to {_plain(low)}")
    if below:
        limits.append(f"less than or equal to {_plain(high)}")
    if (above and number < low) or (below and number > high):
        raise ScriptError(f"Invalid value: must be {' and '.join(limits)}.")
    return value


# Dates and times

_MONTHS = ("January", "February", "March", "April", "May", "June", "July",
           "August", "September", "October", "November", "December")
_DAYS = ("Monday", "Tuesday", "Wednesday", "Thursday", "Friday", "Saturday", "Sunday")
_DATE_FORMATS = ("m/d", "m/d/yy", "mm/dd/yy", "mm/yy", "d-mmm", "d-mmm-yy", "dd-mmm-yy", "yy-mm-dd",
                 "mmm-yy", "mmmm-yy", "mmm d, yyyy", "mmmm d, yyyy", "m/d/yy h:MM tt", "m/d/yy HH:MM")
_TIME_FORMATS = ("HH:MM", "h:MM tt", "HH:MM:ss", "h:MM:ss tt")
_DATE_CODE = re.compile(r"\\.|mmmm|mmm|mm|m|dddd|ddd|dd|d|yyyy|yy|HH|H|hh|h|MM|M|ss|s|tt|t", re.S)
_NAME, _NUM, _MERIDIEM = r"[^\W\d_]+\.?", r"\d{1,2}", r"[ap]\.?m?\.?"
_DATE_SCAN = {  # printd code -> (part, pattern) for reading a date in its own format
    "d": ("d", _NUM), "dd": ("d", _NUM), "ddd": (None, _NAME), "dddd": (None, _NAME),
    "m": ("m", _NUM), "mm": ("m", _NUM), "mmm": ("b", _NAME), "mmmm": ("b", _NAME),
    "yy": ("y", r"\d{2}"), "yyyy": ("y", r"\d{4}"),
    "H": ("H", _NUM), "HH": ("H", _NUM), "h": ("H", _NUM), "hh": ("H", _NUM),
    "M": ("M", _NUM), "MM": ("M", _NUM), "s": ("S", _NUM), "ss": ("S", _NUM),
    "t": ("t", _MERIDIEM), "tt": ("t", _MERIDIEM),
}
_CLOCK = re.compile(
    r"(?<!\d)(?P<H>\d{1,2}):(?P<M>\d{2})(?::(?P<S>\d{2}))?(?:\s*(?P<t>[ap])\.?m?\.?(?![^\W\d_]))?"
    r"|(?<!\d)(?P<H2>\d{1,2})\s*(?P<t2>[ap])\.?m\.?(?![^\W\d_])", re.I)
_FILLER = {"st", "nd", "rd", "th", "of", "at", "t"}


def _printd(fmt: str, when: datetime) -> str:
    hour = when.hour % 12 or 12
    codes = {
        "d": when.day, "dd": f"{when.day:02}", "ddd": _DAYS[when.weekday()][:3], "dddd": _DAYS[when.weekday()],
        "m": when.month, "mm": f"{when.month:02}", "mmm": _MONTHS[when.month - 1][:3],
        "mmmm": _MONTHS[when.month - 1], "yy": f"{when.year % 100:02}", "yyyy": f"{when.year:04}",
        "H": when.hour, "HH": f"{when.hour:02}", "h": hour, "hh": f"{hour:02}",
        "M": when.minute, "MM": f"{when.minute:02}", "s": when.second, "ss": f"{when.second:02}",
        "t": "ap"[when.hour >= 12], "tt": ("am", "pm")[when.hour >= 12],
    }
    return _DATE_CODE.sub(lambda m: m[0][1:] if m[0][0] == "\\" else str(codes[m[0]]), fmt)


@cache
def _date_keys(fmt: str) -> str:
    """Date parts the format shows, in order, as a string of "d", "m", "y"."""
    keys = ""
    for match in _DATE_CODE.finditer(fmt):
        part = _DATE_SCAN.get(match[0], (None,))[0]
        part = "m" if part == "b" else part
        if part in ("d", "m", "y") and part not in keys:
            keys += part
    return keys


def _month(word: str) -> int | None:
    word = word.lower().rstrip(".")
    if len(word) < 3:
        return None
    return next((i for i, name in enumerate(_MONTHS, 1) if name.lower().startswith(word)), None)


def _literal(text: str) -> str:
    return "".join(r"\s*" if c.isspace() else re.escape(c) for c in text)


def _exact_parts(fmt: str, text: str) -> dict | None:
    """Parts of a date written exactly in the format."""
    pattern, seen, end = [], set(), 0
    for match in _DATE_CODE.finditer(fmt):
        pattern.append(_literal(fmt[end:match.start()]))
        end = match.end()
        if match[0][0] == "\\":
            pattern.append(_literal(match[0][1:]))
            continue
        part, body = _DATE_SCAN[match[0]]
        if part and part not in seen:
            seen.add(part)
            body = f"(?P<{part}>{body})"
        pattern.append(body)
    pattern.append(_literal(fmt[end:]))
    match = re.fullmatch("".join(pattern), text, re.I)
    if not match:
        return None
    parts = {k: v for k, v in match.groupdict().items() if v is not None}
    if "b" in parts:
        month = _month(parts.pop("b"))
        if month is None:
            return None
        parts["m"] = str(month)
    if "t" in parts:
        parts["t"] = parts["t"][0].lower()
    return parts


def _loose_parts(fmt: str, text: str) -> dict | None:
    """Parts of a date in any common order, guided by the format (like AFParseDateEx)."""
    parts = {}
    if clock := _CLOCK.search(text):
        found = clock.groupdict()
        parts = {"H": found["H"] or found["H2"], "M": found["M"] or "0", "S": found["S"] or "0"}
        if meridiem := found["t"] or found["t2"]:
            parts["t"] = meridiem.lower()
        text = text[:clock.start()] + " " + text[clock.end():]
    keys = _date_keys(fmt)
    if not keys:
        return parts if clock and not text.strip() else None
    for word in re.findall(r"[^\W\d_]+", text):
        month = _month(word)
        if month and "m" not in parts:
            parts["m"] = str(month)
        elif word.lower() not in _FILLER and not (len(word) >= 3 and any(
                day.lower().startswith(word.lower()) for day in _DAYS)):
            return None
    numbers = re.findall(r"[0-9]+", text)
    order = [k for k in dict.fromkeys(keys + "mdy") if k not in parts]
    long = [n for n in numbers if len(n) > 2]
    if len(numbers) == 3 and len(numbers[0]) > 2 and "m" not in parts:
        order = ["y", "m", "d"]  # ISO
    elif len(long) == 1:
        parts["y"] = long[0]
        numbers.remove(long[0])
        order.remove("y")
    if len(numbers) > len(order):
        return None
    parts.update(zip(order, numbers))
    return parts


def _make_date(fmt: str, parts: dict) -> datetime | None:
    keys = _date_keys(fmt)
    if any(k not in parts for k in keys if k != "y"):
        return None
    try:
        year = parts.get("y")
        if year is None:
            year = date.today().year if keys else 2000
        elif len(year) <= 2:
            year = int(year) + (2000 if int(year) < 50 else 1900)
        hour, minute, second = (int(parts.get(k, 0)) for k in "HMS")
        if meridiem := parts.get("t"):
            if not 1 <= hour <= 12:
                return None
            hour = hour % 12 + 12 * (meridiem == "p")
        return datetime(int(year), int(parts.get("m", 1)), int(parts.get("d", 1)), hour, minute, second)
    except ValueError:
        return None


def _parse_date(fmt: str, text: str) -> datetime | None:
    """A date/time read leniently, trying the format itself first."""
    text = text.strip()
    for scan in (_exact_parts, _loose_parts):
        parts = scan(fmt, text)
        if parts is not None and (when := _make_date(fmt, parts)):
            return when
    return None


def _date_format(value: str, fmt: str) -> str:
    when = _parse_date(fmt, value)
    return value if when is None else _printd(fmt, when)


def _date_format_index(value: str, index: int) -> str:
    return _date_format(value, _pick(_DATE_FORMATS, index))


def _time_format_index(value: str, index: int) -> str:
    return _date_format(value, _pick(_TIME_FORMATS, index))


def _date_keystroke(name: str, value: str, fmt: str) -> str:
    when = _parse_date(fmt, value)
    if when is None:
        raise ScriptError("Invalid date/time: please ensure that the date/time exists. "
                          f"Field [ {name} ] should match format {fmt}")
    return _printd(fmt, when)


def _date_keystroke_index(name: str, value: str, index: int) -> str:
    return _date_keystroke(name, value, _pick(_DATE_FORMATS, index))


def _time_keystroke_index(name: str, value: str, index: int) -> str:
    return _date_keystroke(name, value, _pick(_TIME_FORMATS, index))


# Special formats and masks

_SPECIAL = ("99999", "99999-9999", "(999) 999-9999", "999-99-9999")
_MASK = {"9": lambda c: c in "0123456789", "A": str.isalpha,
         "O": lambda c: c.isalpha() or c in "0123456789", "X": lambda c: True}


def _fit(mask: str, text: str) -> str | None:
    """Text laid out in a mask (9 digit, A letter, O either, X any); literals may be omitted."""
    out, i = [], 0
    for char in mask:
        test = _MASK.get(char)
        if test is None:
            out.append(char)
            if i < len(text) and text[i] == char:
                i += 1
        elif i < len(text) and test(text[i]):
            out.append(text[i])
            i += 1
        else:
            return None
    return "".join(out) if i == len(text) else None


def _special(psf: int, digits: str) -> str | None:
    mask = _pick(_SPECIAL, psf)
    return _fit("999-9999" if psf == 2 and len(digits) == 7 else mask, digits)


def _special_format(value: str, psf: int) -> str:
    return _special(psf, re.sub(r"[^0-9]", "", value)) or value


def _mask_format(value: str, mask: str) -> str:
    return _fit(mask, value) or value


def _special_keystroke(name: str, value: str, psf: int) -> str:
    result = _special(psf, re.sub(r"[\s.()-]", "", value))
    if result is None:
        raise _mismatch(name)
    return result


def _mask_keystroke(name: str, value: str, mask: str) -> str:
    result = _fit(mask, value.strip()) if mask else value
    if result is None:
        raise _mismatch(name)
    return result


